#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_NOTICES.md: every Rust crate linked into the app
 * (normal dependencies reachable from the `librarium` crate, all target
 * platforms) and every npm package bundled into the frontend (non-dev
 * entries of package-lock.json), with version, licence and source URL.
 *
 * Usage: npm run notices   (needs cargo; run after dependency changes)
 *
 * This is an inventory, not legal advice: copyleft licences are listed in
 * their own section so they are easy to review.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EUPL|CDDL|EPL|OSL)/i

// ── Rust ────────────────────────────────────────────────────────────────────
const meta = JSON.parse(execFileSync('cargo', [
    'metadata', '--format-version', '1', '--locked',
    '--manifest-path', join(root, 'src-tauri', 'Cargo.toml'),
], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }))

const pkgById = new Map(meta.packages.map(p => [p.id, p]))
const nodeById = new Map(meta.resolve.nodes.map(n => [n.id, n]))
const rootId = meta.packages.find(p => p.name === 'librarium').id

// Breadth-first walk over normal (not dev, not build) dependency edges.
const seen = new Set([rootId])
const queue = [rootId]
while (queue.length) {
    const node = nodeById.get(queue.shift())
    for (const dep of node?.deps ?? []) {
        const normal = dep.dep_kinds.some(k => k.kind === null)
        if (normal && !seen.has(dep.pkg)) { seen.add(dep.pkg); queue.push(dep.pkg) }
    }
}
seen.delete(rootId)
const crates = [...seen].map(id => pkgById.get(id)).map(p => ({
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? `see ${p.license_file}` : 'UNKNOWN'),
    url: p.repository ?? p.homepage ?? (p.source?.startsWith('registry') ? `https://crates.io/crates/${p.name}` : 'vendored'),
}))

// ── npm ─────────────────────────────────────────────────────────────────────
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'))
const npm = Object.entries(lock.packages)
    .filter(([path, p]) => path.startsWith('node_modules/') && !p.dev && !p.devOptional)
    .map(([path, p]) => {
        const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length)
        const manifest = join(root, path, 'package.json')
        let url = `https://www.npmjs.com/package/${name}`
        if (existsSync(manifest)) {
            const repo = JSON.parse(readFileSync(manifest, 'utf8')).repository
            const raw = typeof repo === 'string' ? repo : repo?.url
            if (raw) { url = raw.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://') }
        }
        return { name, version: p.version, license: p.license ?? 'UNKNOWN', url }
    })

// ── Output ──────────────────────────────────────────────────────────────────
const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
const table = rows => [
    '| Package | Version | Licence | Source |',
    '|---|---|---|---|',
    ...rows.sort(byName).map(r => `| ${r.name} | ${r.version} | ${r.license} | ${r.url} |`),
].join('\n')
const copyleft = [...crates.map(c => ({ ...c, kind: 'Rust' })), ...npm.map(n => ({ ...n, kind: 'npm' }))]
    .filter(r => COPYLEFT.test(r.license))

const out = `# Third-party notices

Librarium includes the open-source components listed below. Generated by
\`npm run notices\` from Cargo.lock and package-lock.json; do not edit by hand.

## Copyleft licences (review)

${copyleft.length ? copyleft.sort(byName).map(r => `- **${r.name} ${r.version}** (${r.kind}): ${r.license}, ${r.url}`).join('\n') : 'None.'}

## Rust crates (${crates.length})

${table(crates)}

## npm packages bundled in the app (${npm.length})

${table(npm)}
`
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out)
console.log(`THIRD_PARTY_NOTICES.md: ${crates.length} crates, ${npm.length} npm packages, ${copyleft.length} copyleft`)
